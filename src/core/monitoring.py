logger = get_logger(__name__)


# Alert level enum
class AlertLevel(Enum):
    """Alert level"""

    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"
    CRITICAL = "CRITICAL"
    EMERGENCY = "EMERGENCY"


# Alert status enum
class AlertStatus(Enum):
    """Alert status"""

    ACTIVE = "ACTIVE"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"
    SUPPRESSED = "SUPPRESSED"


@dataclass
class AlertRule:
    """Alert rule"""

    name: str
    description: str
    condition: str  # Condition expression
    threshold: Union[int, float]
    time_window: int  # Time window (minutes)
    severity: AlertLevel
    enabled: bool = True
    cooldown_period: int = 60  # Cooldown period (minutes)
    notification_channels: List[str] = None

    def __post_init__(self):
        if self.notification_channels is None:
            self.notification_channels = ["log"]


@dataclass
class Alert:
    """Alert information"""

    id: str
    rule_name: str
    message: str
    severity: AlertLevel
    status: AlertStatus
    triggered_at: datetime
    acknowledged_at: Optional[datetime] = None
    resolved_at: Optional[datetime] = None
    context: Dict[str, Any] = None
    notification_sent: bool = False

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary"""
        data = asdict(self)
        data["triggered_at"] = self.triggered_at.isoformat()
        if self.acknowledged_at:
            data["acknowledged_at"] = self.acknowledged_at.isoformat()
        if self.resolved_at:
            data["resolved_at"] = self.resolved_at.isoformat()
        data["severity"] = self.severity.value
        data["status"] = self.status.value
        return data


class NotificationChannel:
    """Notification channel base class"""

    def __init__(self, name: str, config: Dict[str, Any]):
        self.name = name
        self.config = config
        self.enabled = config.get("enabled", True)

    def send_notification(self, alert: Alert) -> bool:
        """Send notification"""
        raise NotImplementedError

    def test_connection(self) -> bool:
        """Test connection"""
        raise NotImplementedError


class EmailNotificationChannel(NotificationChannel):
    """Email notification channel"""

    def send_notification(self, alert: Alert) -> bool:
        """Send email notification"""
        try:
            if not self.enabled:
                return False

            smtp_server = self.config["smtp_server"]
            smtp_port = self.config["smtp_port"]
            username = self.config["username"]
            password = self.config["password"]
            from_addr = self.config["from_address"]
            to_addrs = self.config["to_addresses"]

            # Create email
            msg = MIMEMultipart()
            msg["From"] = from_addr
            msg["To"] = ", ".join(to_addrs)
            msg["Subject"] = (
                f"[{alert.severity.value}] StockInfoDownloader Alert: {alert.rule_name}"
            )

            # Email content
            body = f"""
Alert Details:
- Rule: {alert.rule_name}
- Severity: {alert.severity.value}
- Message: {alert.message}
- Triggered At: {alert.triggered_at.strftime('%Y-%m-%d %H:%M:%S')}
- Status: {alert.status.value}

Context:
{json.dumps(alert.context or {}, indent=2, ensure_ascii=False)}

This alert was generated by StockInfoDownloader Error Monitoring System.
            """

            msg.attach(MIMEText(body, "plain", "utf-8"))

            # Send email
            with smtplib.SMTP(smtp_server, smtp_port) as server:
                server.starttls()
                server.login(username, password)
                server.send_message(msg)

            logger.info(f"Email notification sent successfully: {alert.id}")
            return True

        except Exception as e:
            logger.error(f"Email notification failed: {e}")
            return False

    def test_connection(self) -> bool:
        """Test email server connection"""
        try:
            smtp_server = self.config["smtp_server"]
            smtp_port = self.config["smtp_port"]
            username = self.config["username"]
            password = self.config["password"]

            with smtplib.SMTP(smtp_server, smtp_port) as server:
                server.starttls()
                server.login(username, password)

            logger.info("Email server connection test successful")
            return True

        except Exception as e:
            logger.error(f"Email server connection test failed: {e}")
            return False


class WebhookNotificationChannel(NotificationChannel):
    """Webhook notification channel"""

    def send_notification(self, alert: Alert) -> bool:
        """Send Webhook notification"""
        try:
            if not self.enabled:
                return False

            webhook_url = self.config["webhook_url"]
            headers = self.config.get("headers", {"Content-Type": "application/json"})
            timeout = self.config.get("timeout", 30)

            # Prepare request data
            payload = {
                "alert_id": alert.id,
                "rule_name": alert.rule_name,
                "severity": alert.severity.value,
                "message": alert.message,
                "status": alert.status.value,
                "triggered_at": alert.triggered_at.isoformat(),
                "context": alert.context or {},
            }

            # Send request
            response = requests.post(
                webhook_url, json=payload, headers=headers, timeout=timeout
            )

            if response.status_code == 200:
                logger.info(f"Webhook notification sent successfully: {alert.id}")
                return True
            else:
                logger.error(f"Webhook notification failed: HTTP {response.status_code}")
                return False

        except Exception as e:
            logger.error(f"Webhook notification failed: {e}")
            return False

    def test_connection(self) -> bool:
        """Test Webhook connection"""
        try:
            webhook_url = self.config["webhook_url"]
            timeout = self.config.get("timeout", 30)

            # Send test request
            test_payload = {"test": True, "timestamp": datetime.now().isoformat()}
            response = requests.post(webhook_url, json=test_payload, timeout=timeout)

            if response.status_code == 200:
                logger.info("Webhook connection test successful")
                return True
            else:
                logger.error(f"Webhook connection test failed: HTTP {response.status_code}")
                return False

        except Exception as e:
            logger.error(f"Webhook connection test failed: {e}")
            return False


