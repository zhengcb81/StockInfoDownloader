class ErrorMonitoringSystem:
    """Error monitoring system"""

    def __init__(self, config: Dict[str, Any]):
        """
        Initialize error monitoring system

        Args:
            config: Monitoring system configuration
        """
        self.config = config
        self.alert_rules: List[AlertRule] = []
        self.active_alerts: Dict[str, Alert] = {}
        self.notification_channels: Dict[str, NotificationChannel] = {}
        self.alert_history: List[Alert] = []
        self.max_history_size = 1000

        # Initialize notification channels
        self._initialize_notification_channels()

        # Load default alert rules
        self._load_default_rules()

        # Start monitoring loop
        self.running = False
        self.monitor_thread = None

    def _initialize_notification_channels(self):
        """Initialize notification channels"""
        channels_config = self.config.get("notification_channels", {})

        for channel_name, channel_config in channels_config.items():
            channel_type = channel_config.get("type")

            if channel_type == "email":
                self.notification_channels[channel_name] = EmailNotificationChannel(
                    channel_name, channel_config
                )
            elif channel_type == "webhook":
                self.notification_channels[channel_name] = WebhookNotificationChannel(
                    channel_name, channel_config
                )
            elif channel_type == "slack":
                self.notification_channels[channel_name] = SlackNotificationChannel(
                    channel_name, channel_config
                )
            else:
                logger.warning(f"Unknown notification channel type: {channel_type}")

    def _load_default_rules(self):
        """Load default alert rules"""
        default_rules = [
            AlertRule(
                name="high_error_rate",
                description="High error rate alert",
                condition="error_rate > threshold",
                threshold=0.1,  # 10%
                time_window=5,  # 5 minutes
                severity=AlertLevel.WARNING,
                notification_channels=["log", "email"],
            ),
            AlertRule(
                name="critical_error_count",
                description="Critical error count alert",
                condition="critical_error_count > threshold",
                threshold=5,
                time_window=10,
                severity=AlertLevel.ERROR,
                notification_channels=["log", "email", "slack"],
            ),
            AlertRule(
                name="recovery_failure",
                description="Error recovery failure alert",
                condition="recovery_failure_rate > threshold",
                threshold=0.5,  # 50%
                time_window=15,
                severity=AlertLevel.CRITICAL,
                notification_channels=["log", "email", "slack"],
            ),
            AlertRule(
                name="system_unavailable",
                description="System unavailable alert",
                condition="system_unavailable",
                threshold=1,
                time_window=1,
                severity=AlertLevel.EMERGENCY,
                notification_channels=["log", "email", "slack"],
            ),
        ]

        for rule in default_rules:
            self.add_alert_rule(rule)

    def add_alert_rule(self, rule: AlertRule):
        """Add alert rule"""
        self.alert_rules.append(rule)
        logger.info(f"Alert rule added: {rule.name}")

    def remove_alert_rule(self, rule_name: str):
        """Remove alert rule"""
        self.alert_rules = [rule for rule in self.alert_rules if rule.name != rule_name]
        logger.info(f"Alert rule removed: {rule_name}")

    def start_monitoring(self):
        """Start monitoring"""
        if self.running:
            logger.warning("Monitoring system is already running")
            return

        self.running = True
        logger.info("Starting error monitoring system")

        # Start monitoring thread
        import threading

        self.monitor_thread = threading.Thread(
            target=self._monitoring_loop, daemon=True
        )
        self.monitor_thread.start()

    def stop_monitoring(self):
        """Stop monitoring"""
        self.running = False
        if self.monitor_thread:
            self.monitor_thread.join(timeout=5)
        logger.info("Stopping error monitoring system")

    def _monitoring_loop(self):
        """Monitoring loop"""
        while self.running:
            try:
                # Check all alert rules
                for rule in self.alert_rules:
                    if rule.enabled:
                        self._check_alert_rule(rule)

                # Clean up resolved alerts
                self._cleanup_resolved_alerts()

                # Wait for next check
                time.sleep(60)  # Check every minute

            except Exception as e:
                logger.error(f"Monitoring loop error: {e}")
                time.sleep(60)

    def _check_alert_rule(self, rule: AlertRule):
        """Check alert rule"""
        try:
            # Get error statistics
            error_stats = error_logger.get_error_summary(hours=rule.time_window // 60)

            # Check cooldown period
            if rule.name in self.active_alerts:
                active_alert = self.active_alerts[rule.name]
                if (
                    datetime.now() - active_alert.triggered_at
                ).total_seconds() < rule.cooldown_period * 60:
                    return  # In cooldown period, do not trigger again

            # Evaluate rule condition
            should_alert = self._evaluate_rule_condition(rule, error_stats)

            if should_alert:
                self._trigger_alert(rule, error_stats)

        except Exception as e:
            logger.error(f"Failed to check alert rule {rule.name}: {e}")

    def _evaluate_rule_condition(self, rule: AlertRule, stats: Dict[str, Any]) -> bool:
        """Evaluate rule condition"""
        try:
            if rule.condition == "error_rate > threshold":
                error_rate = stats.get("error_frequency", 0)
                return error_rate > rule.threshold

            elif rule.condition == "critical_error_count > threshold":
                critical_count = stats.get("severities", {}).get("CRITICAL", 0)
                return critical_count > rule.threshold

            elif rule.condition == "recovery_failure_rate > threshold":
                recovery_rate = stats.get("recovery_rate", 1.0)
                failure_rate = 1.0 - recovery_rate
                return failure_rate > rule.threshold

            elif rule.condition == "system_unavailable":
                # Check if system is available
                total_errors = stats.get("total_errors", 0)
                return total_errors > rule.threshold

            return False

        except Exception as e:
            logger.error(f"Failed to evaluate rule condition {rule.name}: {e}")
            return False

    def _trigger_alert(self, rule: AlertRule, context: Dict[str, Any]):
        """Trigger alert"""
        try:
            # Create alert
            alert = Alert(
                id=f"{rule.name}_{int(time.time())}",
                rule_name=rule.name,
                message=f"Alert rule {rule.name} triggered",
                severity=rule.severity,
                status=AlertStatus.ACTIVE,
                triggered_at=datetime.now(),
                context=context,
            )

            # Store alert
            self.active_alerts[rule.name] = alert
            self.alert_history.append(alert)

            # Limit history size
            if len(self.alert_history) > self.max_history_size:
                self.alert_history = self.alert_history[-self.max_history_size :]

            # Send notifications
            self._send_alert_notifications(alert)

            logger.warning(f"Alert triggered: {rule.name} - {alert.message}")

        except Exception as e:
            logger.error(f"Failed to trigger alert {rule.name}: {e}")

    def _send_alert_notifications(self, alert: Alert):
        """Send alert notification"""
        try:
            for channel_name in alert.rule.notification_channels:
                if channel_name in self.notification_channels:
                    channel = self.notification_channels[channel_name]

                    if channel.send_notification(alert):
                        alert.notification_sent = True
                        logger.info(f"Alert notification sent successfully: {alert.id} -> {channel_name}")
                    else:
                        logger.error(f"Alert notification failed: {alert.id} -> {channel_name}")
                else:
                    logger.warning(f"Notification channel not found: {channel_name}")

        except Exception as e:
            logger.error(f"Failed to send alert notification: {e}")

    def _cleanup_resolved_alerts(self):
        """Clean up resolved alerts"""
        try:
            resolved_alerts = []

            for alert_id, alert in self.active_alerts.items():
                # Check if alert should be marked as resolved
                if self._should_resolve_alert(alert):
                    alert.status = AlertStatus.RESOLVED
                    alert.resolved_at = datetime.now()
                    resolved_alerts.append(alert_id)

                    logger.info(f"Alert resolved: {alert.rule_name}")

            # Remove resolved alerts from active alerts
            for alert_id in resolved_alerts:
                del self.active_alerts[alert_id]

        except Exception as e:
            logger.error(f"Failed to clean up resolved alerts: {e}")

    def _should_resolve_alert(self, alert: Alert) -> bool:
        """Determine if alert should be resolved"""
        try:
            # Get latest error stats
            recent_stats = error_logger.get_error_summary(hours=1)

            # Determine if should resolve based on alert type
            if alert.rule_name == "high_error_rate":
                error_rate = recent_stats.get("error_frequency", 0)
                return error_rate < 0.05  # Error rate below 5%

            elif alert.rule_name == "critical_error_count":
                critical_count = recent_stats.get("severities", {}).get("CRITICAL", 0)
                return critical_count == 0  # No critical errors

            elif alert.rule_name == "recovery_failure":
                recovery_rate = recent_stats.get("recovery_rate", 1.0)
                return recovery_rate > 0.8  # Recovery rate above 80%

            elif alert.rule_name == "system_unavailable":
                total_errors = recent_stats.get("total_errors", 0)
                return total_errors == 0  # No errors

            return False

        except Exception as e:
            logger.error(f"Failed to determine alert resolution status: {e}")
            return False

    def acknowledge_alert(self, alert_id: str) -> bool:
        """Acknowledge alert"""
        try:
            for alert in self.active_alerts.values():
                if alert.id == alert_id:
                    alert.status = AlertStatus.ACKNOWLEDGED
                    alert.acknowledged_at = datetime.now()
                    logger.info(f"Alert acknowledged: {alert_id}")
                    return True

            return False

        except Exception as e:
            logger.error(f"Failed to acknowledge alert: {e}")
            return False

    def get_alert_status(self) -> Dict[str, Any]:
        """Get alert status"""
        try:
            return {
                "active_alerts": len(self.active_alerts),
                "total_alerts": len(self.alert_history),
                "alerts_by_severity": self._get_alerts_by_severity(),
                "recent_alerts": [
                    alert.to_dict() for alert in self.alert_history[-10:]
                ],
                "notification_channels": {
                    name: {"enabled": channel.enabled, "type": type(channel).__name__}
                    for name, channel in self.notification_channels.items()
                },
            }

        except Exception as e:
            logger.error(f"Failed to get alert status: {e}")
            return {"error": str(e)}

    def _get_alerts_by_severity(self) -> Dict[str, int]:
        """Count alerts by severity level"""
        severity_count = {}

        for alert in self.active_alerts.values():
            severity = alert.severity.value
            severity_count[severity] = severity_count.get(severity, 0) + 1

        return severity_count

    def test_notification_channels(self) -> Dict[str, bool]:
        """Test all notification channels"""
        results = {}

        for name, channel in self.notification_channels.items():
            try:
                results[name] = channel.test_connection()
            except Exception as e:
                logger.error(f"Failed to test notification channel {name}: {e}")
                results[name] = False

        return results

    def export_alert_report(self, output_path: str, days: int = 7) -> bool:
        """Export alert report"""
        try:
            cutoff_time = datetime.now() - timedelta(days=days)
            recent_alerts = [
                alert
                for alert in self.alert_history
                if alert.triggered_at >= cutoff_time
            ]

            report_data = {
                "generated_at": datetime.now().isoformat(),
                "period_days": days,
                "total_alerts": len(recent_alerts),
                "alerts_by_severity": self._get_alerts_by_severity(),
                "alerts": [alert.to_dict() for alert in recent_alerts],
            }

            with open(output_path, "w", encoding="utf-8") as f:
                json.dump(report_data, f, ensure_ascii=False, indent=2)

            logger.info(f"Alert report exported to: {output_path}")
            return True

        except Exception as e:
            logger.error(f"Failed to export alert report: {e}")
            return False


# Global monitoring system instance
_monitoring_system = None


def get_monitoring_system(config: Dict[str, Any] = None) -> ErrorMonitoringSystem:
    """Get global monitoring system instance"""
    global _monitoring_system

    if _monitoring_system is None:
        if config is None:
            config = {
                "notification_channels": {"log": {"type": "log", "enabled": True}}
            }

        _monitoring_system = ErrorMonitoringSystem(config)

    return _monitoring_system


def start_monitoring(config: Dict[str, Any] = None):
    """Start error monitoring"""
    system = get_monitoring_system(config)
    system.start_monitoring()


def stop_monitoring():
    """Stop error monitoring"""
    global _monitoring_system
    if _monitoring_system:
        _monitoring_system.stop_monitoring()


def get_alert_status() -> Dict[str, Any]:
    """Get alert status"""
    global _monitoring_system
    if _monitoring_system:
        return _monitoring_system.get_alert_status()
    return {"error": "Monitoring system not initialized"}


def acknowledge_alert(alert_id: str) -> bool:
    """Acknowledge alert"""
    global _monitoring_system
    if _monitoring_system:
        return _monitoring_system.acknowledge_alert(alert_id)
    return False
